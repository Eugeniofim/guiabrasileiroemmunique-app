let LANG = (function () { try { return JSON.parse(localStorage.getItem(DB_KEY))?.settings?.lang || 'pt'; } catch (e) { return 'pt'; } })();

function t(key, vars) {
  const e = STR[key];
  let s = e ? (e[LANG] ?? e.pt) : key;
  if (Array.isArray(s)) return s;
  if (vars) for (const k in vars) s = s.replaceAll('{' + k + '}', vars[k]);
  /* quem e o guia entra em toda string: {guia}, {negocio}, {base} */
  if (typeof guiaNome === 'function' && s.includes('{'))
    s = s.replaceAll('{guia}', guiaNome()).replaceAll('{negocio}', guiaNegocio()).replaceAll('{base}', guiaBase());
  return s;
}
function setLang(l) { LANG = l; DB.settings.lang = l; save(); }
/* Valor redondo sem centavos (€ 420); com centavos, sempre os dois (€ 1,50 —
   nao "€ 1,5", que foi como os fones do Vaticano apareceram). */
function eur(n) {
  const v = Number(n), redondo = Number.isInteger(Math.round(v * 100) / 100) && v % 1 === 0;
  return '€ ' + v.toLocaleString(LANG === 'pt' ? 'pt-BR' : 'en-GB',
    redondo ? {} : { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}
function fmtDate(iso) {
  const d = new Date(iso + 'T12:00:00');
  return LANG === 'pt'
    ? d.toLocaleDateString('pt-BR', { weekday: 'short', day: '2-digit', month: '2-digit' })
    : d.toLocaleDateString('en-GB', { weekday: 'short', day: 'numeric', month: 'short' });
}
